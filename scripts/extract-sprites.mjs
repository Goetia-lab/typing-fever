// Ekstrak sprite dari art/koki.px.js (pxl) jadi sprites.js untuk game.
// Butuh pxl CLI: node C:\Users\acer\.claude\skills\pxl-pixel-art\bin\pxl.js ascii ...
// Jalankan dari root repo: node scripts/extract-sprites.mjs
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PXL = process.argv[2] || 'C:\\Users\\acer\\.claude\\skills\\pxl-pixel-art\\bin\\pxl.js';
const ART = join(root, 'art', 'koki.px.js');
const POSES = ['idle', 'blink', 'happy', 'sleep', 'fever'];

function asciiMap(name) {
  const out = execFileSync('node', [PXL, 'ascii', ART, name], { encoding: 'utf8' });
  const rows = [];
  for (const line of out.split(/\r?\n/)) {
    const m = line.match(/^\s*(\d+)\s+([A-Za-z.]{20,40})\s*$/);
    if (m) rows[+m[1]] = m[2];
  }
  if (rows.length !== 32 || rows.some((r) => r === undefined)) {
    throw new Error(name + ': expected 32 rows, got ' + rows.filter(Boolean).length);
  }
  return rows;
}

const maps = {};
for (const p of POSES) maps[p] = asciiMap('koki_' + p);

// palette harus sama dengan art/koki.px.js
const pal = {
  k: '#241823', l: '#ffb870', o: '#ef9445', O: '#c56a2e',
  c: '#f7e9cf', C: '#dcc49a', w: '#fff8f0', g: '#58b368', G: '#2e7d4f',
  p: '#e8838f', P: '#c4536b', b: '#8a5a3a', B: '#6a4028',
  d: '#402418', s: '#cfc3e8', y: '#ffd75e',
};

const header =
  '// Typing Fever \u00b7 data sprite KOKI\n' +
  '// GENERATED by scripts/extract-sprites.mjs \u2014 jangan edit manual.\n' +
  '// Sumber: art/koki.px.js (pxl). Regenerate: node scripts/extract-sprites.mjs\n' +
  "'use strict';\n\n";

let js = header;
js += 'window.KOKI_PAL = ' + JSON.stringify(pal) + ';\n\n';
js += 'window.KOKI_MAPS = {\n';
for (const p of POSES) {
  js += '  ' + p + ': [\n' + maps[p].map((r) => '    "' + r + '"').join(',\n') + '\n  ],\n';
}
js += '};\n';

writeFileSync(join(root, 'sprites.js'), js, 'utf8');
console.log('sprites.js written: ' + POSES.join(', '));
